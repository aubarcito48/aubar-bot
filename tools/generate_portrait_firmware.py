"""Pack supplied portraits into a shared-palette, zlib-compressed ESP32 asset bank.

Explicit authoring operation. No network, image generation or source modifications.
Run again after moving the checkout: the assembly include uses an absolute path.
"""
from pathlib import Path
import argparse
import json
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "newAUBAR/tramo-01-base-miradas"
DEST = ROOT / "firmware/KirbyPantalla"
WIDTH, HEIGHT = 172, 320
BACKGROUND = (13, 17, 23)


def screen(source):
    from PIL import Image
    with Image.open(source) as image:
        frame = image.convert("RGBA")
        frame.thumbnail((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    result = Image.new("RGB", (WIDTH, HEIGHT), BACKGROUND)
    result.paste(frame, ((WIDTH-frame.width)//2, (HEIGHT-frame.height)//2), frame)
    return result


def write_assembly_paths():
    """Refresh checkout-specific paths without regenerating the asset bank."""
    asset_path = (DEST / "portrait_assets.dat").as_posix()
    (DEST / "portrait_asset_path.h").write_text(
        '// Generated local assembly path. Regenerate after moving the checkout.\n'
        f'#define AUBAR_PORTRAIT_DATA_FILE "{asset_path}"\n', encoding="utf-8")
    (DEST / "portrait_assets.S").write_text(
        '#include "portrait_asset_path.h"\n.section .rodata.aubarPortraitData,"a"\n'
        '.balign 4\n.global aubarPortraitData\naubarPortraitData:\n'
        '.incbin AUBAR_PORTRAIT_DATA_FILE\n', encoding="utf-8")


def main():
    from PIL import Image, ImageDraw
    groups = [
        ("Vertical", [SOURCE / "frames-preparados/vertical/sin-fondo" / f"{i:03d}.webp" for i in range(240)]),
        ("Horizontal", [SOURCE / "frames-preparados/horizontal/sin-fondo" / f"{i:03d}.webp" for i in range(240)]),
        ("Stills", [SOURCE / "animaciones-sin-fondo/formato webp" / f"{n}-Photoroom.webp"
                    for n in ["frente", "mira-pc", "pensando", "dormido", "boca-semi-abierta", "boca-abierta"]]),
        ("Speech", [ROOT / "newAUBAR/tramo-04-hablar/frames-preparados/hablar/sin-fondo" / f"{i:03d}.webp" for i in range(36,216)]),
    ]
    # A single palette prevents independent quantizers from changing skin colors
    # between adjacent frames. No dithering: avoid temporal speckles at LCD size.
    samples = [screen(p).resize((86, 160)) for _, paths in groups
               for i, p in enumerate(paths) if len(paths) < 24 or i % 12 == 0]
    palette_sample = Image.new("RGB", (86 * len(samples), 160))
    for i, sample in enumerate(samples):
        palette_sample.paste(sample, (86*i, 0))
    palette = palette_sample.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    rgb_palette = palette.getpalette()
    colors = [((rgb_palette[i] >> 3) << 11) | ((rgb_palette[i+1] >> 2) << 5)
              | (rgb_palette[i+2] >> 3) for i in range(0, 768, 3)]
    offsets, lengths, records, previews = [], [], [], []
    blob = bytearray()
    bases = {}
    for name, paths in groups:
        bases[name] = len(offsets)
        for i, path in enumerate(paths):
            image = screen(path)
            indexed = image.quantize(palette=palette, dither=Image.Dither.NONE)
            raw = indexed.tobytes()
            compressed = zlib.compress(raw, level=9)
            assert zlib.decompress(compressed) == raw
            offsets.append(len(blob)); lengths.append(len(compressed))
            blob.extend(compressed)
            records.append({"id": len(offsets)-1, "source": path.relative_to(ROOT).as_posix()})
            if (name in ("Vertical", "Horizontal") and i in (0,42,72,126,156,198,222)) or name == "Stills":
                previews.append((f"{name} {i}", indexed.convert("RGB")))
        print(f"{name}: {len(paths)} frames", flush=True)
    if len(blob) > 11_900_000:
        raise ValueError(f"Asset bank exceeds the reserved 12 MiB application budget: {len(blob)}")
    (DEST / "portrait_assets.dat").write_bytes(blob)
    header = ["#pragma once", "#include <stdint.h>",
              "// Generated by tools/generate_portrait_firmware.py; original sources stay intact.",
              f"constexpr uint16_t PORTRAIT_WIDTH={WIDTH}, PORTRAIT_HEIGHT={HEIGHT};",
              f"constexpr uint16_t PORTRAIT_FRAME_COUNT={len(offsets)};",
              "constexpr uint32_t PORTRAIT_PIXELS=PORTRAIT_WIDTH*PORTRAIT_HEIGHT;",
              "constexpr uint16_t PORTRAIT_BACKGROUND=0x0882;",
              'extern "C" const uint8_t aubarPortraitData[];']
    for name, base in bases.items():
        header.append(f"constexpr uint16_t PORTRAIT_{name.upper()}={base};")
    header.append('constexpr uint16_t PORTRAIT_SPEECH_COUNT=180;')
    header += ["constexpr uint16_t PORTRAIT_PALETTE[] = {" + ",".join(f"0x{x:04x}" for x in colors) + "};",
               "constexpr uint32_t PORTRAIT_OFFSETS[] = {" + ",".join(map(str, offsets)) + "};",
               "constexpr uint32_t PORTRAIT_LENGTHS[] = {" + ",".join(map(str, lengths)) + "};"]
    (DEST / "portrait_assets.h").write_text("\n".join(header)+"\n", encoding="utf-8")
    write_assembly_paths()
    review = SOURCE / "frames-preparados/firmware"
    review.mkdir(exist_ok=True)
    sheet = Image.new("RGB", (WIDTH*5, (HEIGHT+24)*((len(previews)+4)//5)), "#243448")
    for i, (name, image) in enumerate(previews):
        x, y = i%5*WIDTH, i//5*(HEIGHT+24)
        sheet.paste(image, (x,y))
        ImageDraw.Draw(sheet).text((x+4,y+HEIGHT+3), name, fill="white")
    sheet.save(review / "lcd-172x320.jpg", quality=92)
    (review / "asset-map.json").write_text(json.dumps({"assetBytes":len(blob),
        "paletteColors":256, "width":WIDTH,"height":HEIGHT,"frames":records}, indent=2)+"\n",encoding="utf-8")
    print(f"Packed {len(offsets)} frames into {len(blob):,} bytes; LCD preview: {review}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh-path', action='store_true',
                        help='Refresh the local assembly path; keep the supplied bank unchanged')
    args = parser.parse_args()
    if args.refresh_path:
        if not (DEST / 'portrait_assets.dat').is_file():
            parser.error('portrait_assets.dat is missing; prepare and pack the source frames first')
        write_assembly_paths()
        print('Local asset path refreshed; firmware bank unchanged.')
    else:
        main()
